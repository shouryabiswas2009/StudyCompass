// Writes supabase/featured/featured.sql from the rule in
// scripts/relevance-rule.mjs and data/curated/featured_us.csv, and prints how
// many of the imported US schools it features.
//
//   npm run data:featured
//
// Run the written file in the Supabase SQL Editor after migration_010, and
// again whenever the rule, the curated list or the Scorecard import changes.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { RELEVANCE_RULE, featuredSql, isFeatured, readCuratedIds } from "./relevance-rule.mjs";
import { EXISTING_SCHOOL_IDS } from "./scorecard/config.mjs";

const ROOT = join(import.meta.dirname, "..");
const curated = readCuratedIds();
const { universities, data_year } = JSON.parse(
  readFileSync(join(ROOT, "data", "scorecard", "universities.json"), "utf8")
);

// The 14 original sample schools keep their (illustrative) QS ranking in the
// database, which the import file doesn't have, so mark them ranked here.
const sampleIds = new Set(Object.values(EXISTING_SCHOOL_IDS));
const rows = universities.map((u) => ({
  ...u,
  qs_ranking: sampleIds.has(u.scorecard_id) ? 1 : null,
}));
const featured = rows.filter((row) => isFeatured(row, curated));

const header = `-- Unicelerate: which shared universities are featured (shown by default).
-- Generated by scripts/build-featured-sql.mjs from the rule in
-- scripts/relevance-rule.mjs and data/curated/featured_us.csv. Don't edit by hand.
-- Rule: R1/R2 research OR SAT 75th percentile >= ${RELEVANCE_RULE.minSat75} OR a known ranking
-- OR hand-curated; every non-Scorecard shared school is always featured.
-- Expected: ${featured.length} of ${rows.length} College Scorecard schools (data year ${data_year}).
-- Run after migration_010. Safe to re-run.
`;

mkdirSync(join(ROOT, "supabase", "featured"), { recursive: true });
writeFileSync(join(ROOT, "supabase", "featured", "featured.sql"), header + "\n" + featuredSql(curated));

const count = (pred) => rows.filter(pred).length;
console.log(`Featured: ${featured.length} of ${rows.length} College Scorecard schools`);
console.log(`  R1/R2: ${count((r) => RELEVANCE_RULE.researchLevels.includes(r.research_intensity))}`);
console.log(`  SAT 75th >= ${RELEVANCE_RULE.minSat75}: ${count((r) => r.sat_75 >= RELEVANCE_RULE.minSat75)}`);
console.log(`  hand-curated: ${curated.length}`);
console.log("Wrote supabase/featured/featured.sql");
