// Validates data/curated/country_info.csv and writes
// supabase/seed_country_info.sql (run it in the SQL Editor after
// migration_012). Nothing is written if a check fails.
//
//   npm run data:validate-country-info   (check only)
//   npm run data:build-country-info
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { canonicalCountry } from "../../lib/countries.ts";
import { parseCsv } from "./csv.mjs";
import { countryInfoSql, validateCountryInfo } from "./country-info-lib.mjs";

const ROOT = join(import.meta.dirname, "..", "..");
const read = (file) => parseCsv(readFileSync(join(ROOT, "data", "curated", file), "utf8"));

const records = read("country_info.csv");

// Every country that has schools: the curated international list, plus the
// United States (College Scorecard).
const required = [
  ...new Set(["United States", ...read("international_universities.csv").map((r) => canonicalCountry(r.country))]),
].sort();

const { errors } = validateCountryInfo(records, required);
// Country names must be the canonical ones the app uses for matching.
for (const r of records) {
  if (r.country && canonicalCountry(r.country) !== r.country) {
    errors.push(`line ${r._line}: use the canonical name "${canonicalCountry(r.country)}", not "${r.country}"`);
  }
}
if (errors.length) {
  for (const e of errors) console.error(`ERROR    country_info.csv ${e}`);
  console.error("Nothing written: fix the errors above first.");
  process.exit(1);
}

const filled = (prefix) => records.filter((r) => r[`${prefix}_text`]).length;
const summary = `${records.length} countries; post-study ${filled("post_study")}, proof of funds ${filled("funds")}, work hours ${filled("work")} filled in`;

if (process.argv.includes("--check")) {
  console.log(`OK  ${summary}: no errors`);
  process.exit(0);
}

const header = [
  "-- Generated by `npm run data:build-country-info` from data/curated/country_info.csv.",
  "-- Do not edit by hand: edit the CSV and re-run the script.",
  "-- Run after migration_012_country_info.sql. Safe to run more than once.",
  `-- ${summary}.`,
  "",
].join("\n");
writeFileSync(join(ROOT, "supabase", "seed_country_info.sql"), header + countryInfoSql(records));
console.log(`Wrote supabase/seed_country_info.sql: ${summary}`);
