// Writes supabase/seed_scorecard/*.sql from data/scorecard/universities.json.
// Run the files in order in the Supabase SQL Editor (after migrations 007 and 008).
//
//   npm run data:build-scorecard-sql
//
// The SQL "upserts": a school already imported (same scorecard_id) gets its
// official figures updated; a new one is inserted. Names, descriptions and
// the illustrative rankings are never overwritten.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EXISTING_SCHOOL_IDS } from "./config.mjs";

const ROOT = join(import.meta.dirname, "..", "..");
const OUT_DIR = join(ROOT, "supabase", "seed_scorecard");
const BATCH_SIZE = 300; // keeps each file small enough for the SQL Editor

const { universities, data_year, fetched_at } = JSON.parse(
  readFileSync(join(ROOT, "data", "scorecard", "universities.json"), "utf8")
);

// Values → SQL literals. Strings are quoted with '' escaping; arrays become
// text[]; missing values become null.
function sql(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (Array.isArray(value)) {
    return value.length ? `array[${value.map(sql).join(", ")}]::text[]` : "'{}'::text[]";
  }
  return `'${String(value).replaceAll("'", "''")}'`;
}

const COLUMNS = [
  "scorecard_id", "name", "country", "city", "state", "ownership", "us_region",
  "tuition", "tuition_in_state", "avg_net_price", "acceptance_rate", "sat_25", "sat_75",
  "avg_admitted_gpa", "min_ielts", "living_cost_per_year", "student_size",
  "completion_rate", "retention_rate", "research_intensity", "median_earnings_10yr",
  "popular_programs", "degree_levels",
  "description", "source", "data_year", "fetched_at", "source_url",
];

// Columns refreshed when a school is already in the table. Not name or
// description (they may have been tidied by hand), and not the illustrative
// rankings, which Scorecard doesn't have.
const UPDATED = COLUMNS.filter((c) => !["scorecard_id", "name", "description"].includes(c));

const header = (part, total) => `-- Unicelerate: College Scorecard import, part ${part} of ${total}
-- Generated by scripts/scorecard/build-seed-sql.mjs from data/scorecard/universities.json.
-- Source: US Department of Education College Scorecard, data year ${data_year},
-- fetched ${fetched_at}. Run after migrations 007 and 008, files in order.
`;

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const batches = [];
for (let i = 0; i < universities.length; i += BATCH_SIZE) {
  batches.push(universities.slice(i, i + BATCH_SIZE));
}
const totalParts = batches.length + 1;

// Part 0: link the hand-written sample schools that Scorecard also covers,
// so the upsert updates them in place (keeping students' saves and
// applications attached) instead of creating duplicates.
const links = Object.entries(EXISTING_SCHOOL_IDS)
  .map(
    ([name, id]) =>
      `update public.universities set scorecard_id = ${id}\n  where name = ${sql(name)} and created_by is null and scorecard_id is null;`
  )
  .join("\n");
writeFileSync(
  join(OUT_DIR, "00_link_existing.sql"),
  header(0, totalParts - 1) +
    "\n-- Their figures become official; their names and illustrative rankings stay.\n" +
    links +
    "\n"
);

batches.forEach((batch, i) => {
  const values = batch.map((row) => `  (${COLUMNS.map((c) => sql(row[c])).join(", ")})`).join(",\n");
  const statement = `insert into public.universities (${COLUMNS.join(", ")})
values
${values}
on conflict (scorecard_id) do update set
${UPDATED.map((c) => `  ${c} = excluded.${c}`).join(",\n")}
where universities.created_by is null;
`;
  const name = `${String(i + 1).padStart(2, "0")}_universities.sql`;
  writeFileSync(join(OUT_DIR, name), header(i + 1, totalParts - 1) + "\n" + statement);
});

console.log(
  `Wrote ${totalParts} files to supabase/seed_scorecard/ (${universities.length} schools, ${BATCH_SIZE} per file)`
);
console.log(readdirSync(OUT_DIR).join("\n"));
